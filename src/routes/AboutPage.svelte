<section>
  <h1>About Bihua</h1>
  <p>
    Look up a character by pinyin and follow its stroke order while writing on paper. Nothing you
    search or view is stored or sent anywhere; only your display preferences are remembered in this
    browser.
  </p>
  <p>
    Stroke order follows the PRC standard for both Simplified and Traditional characters. HSK levels
    are from HSK 3.0 (2021); levels 7–9 form one band.
  </p>

  <h2>Data</h2>
  <ul>
    <li>
